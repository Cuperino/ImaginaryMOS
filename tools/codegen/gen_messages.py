"""Generate the MOS message registry and typed views from the spec schemas.

Implements the code-generation step of plan §4.5: the DTD extracted from the
spec (fixtures/schema/mos4.dtd) carries the content models; a hand-maintained
annotations file (tools/codegen/annotations.json) carries channel assignment,
profile membership, request/response pairing, and the content models the
printed DTD omits. Output is checked into the tree under core/; a CTest gate
regenerates and diffs so the generated code cannot drift from its inputs.

Usage:
    gen_messages.py <mos4.dtd> <annotations.json> <output-root>

Writes, under <output-root> (normally the repo's core/ directory):
    include/imos/codec/gen/message_types.h
    include/imos/codec/gen/views.h
    codec/gen/message_types.cpp
"""

from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

BANNER = """\
// SPDX-FileCopyrightText: 2026 Javier O. Cordero Pérez
// SPDX-License-Identifier: Apache-2.0
//
// GENERATED by tools/codegen/gen_messages.py from fixtures/schema/mos4.dtd
// and tools/codegen/annotations.json — DO NOT EDIT. Regenerate with:
//   python3 tools/codegen/gen_messages.py fixtures/schema/mos4.dtd
//       tools/codegen/annotations.json core        (single command line)
"""

# ---------------------------------------------------------------- DTD parsing


@dataclass
class ChildSpec:
    name: str
    optional: bool = False
    repeated: bool = False
    order: int = 0


@dataclass
class ElementDecl:
    name: str
    model: str  # raw content model text
    children: list[ChildSpec] = field(default_factory=list)
    attributes: list[str] = field(default_factory=list)

    @property
    def kind(self) -> str:
        m = self.model.strip()
        if m == "EMPTY":
            return "empty"
        if m == "ANY":
            return "any"
        if re.fullmatch(r"\(\s*#PCDATA\s*\)\*?", m):
            return "scalar"
        if "#PCDATA" in m:
            return "mixed"
        return "struct"


def parse_dtd(text: str) -> dict[str, ElementDecl]:
    decls: dict[str, ElementDecl] = {}
    for m in re.finditer(r"<!ELEMENT\s+([\w:-]+)\s+(.*?)>", text, re.S):
        name, model = m.group(1), re.sub(r"\s+", " ", m.group(2)).strip()
        # First declaration wins (the spec DTD contains a duplicate mosProfile).
        decls.setdefault(name, ElementDecl(name, model))
    for m in re.finditer(r"<!ATTLIST\s+([\w:-]+)\s+(.*?)>", text, re.S):
        name, body = m.group(1), m.group(2)
        if name not in decls:
            continue
        for am in re.finditer(r"([\w:.-]+)\s+(?:CDATA|\([^)]*\)|ID|IDREF|NMTOKEN)", body):
            attr = am.group(1)
            if attr not in decls[name].attributes and not attr.startswith("xml:"):
                decls[name].attributes.append(attr)
    return decls


def flatten_model(model: str) -> list[ChildSpec]:
    """Flatten a DTD content model into an ordered child list.

    Choices make every alternative optional; * / + on a group propagates
    repetition to its members. A name that occurs more than once collapses to
    a single repeated entry (e.g. roStoryMove's two storyIDs).
    """
    tokens = re.findall(r"[\w:#-]+|[(),|?*+]", model)
    pos = 0

    def parse_group() -> tuple[list[ChildSpec], bool]:
        nonlocal pos
        assert tokens[pos] == "("
        pos += 1
        items: list[ChildSpec] = []
        is_choice = False
        while tokens[pos] != ")":
            tok = tokens[pos]
            if tok == "|":
                is_choice = True
                pos += 1
            elif tok == ",":
                pos += 1
            elif tok == "(":
                sub, _ = parse_group()
                items.extend(sub)
            elif tok == "#PCDATA":
                pos += 1
            else:
                pos += 1
                spec = ChildSpec(tok)
                if pos < len(tokens) and tokens[pos] in "?*+":
                    spec.optional = tokens[pos] in "?*"
                    spec.repeated = tokens[pos] in "*+"
                    pos += 1
                items.append(spec)
        pos += 1  # ')'
        if pos < len(tokens) and tokens[pos] in "?*+":
            suffix = tokens[pos]
            pos += 1
            for it in items:
                it.optional = it.optional or suffix in "?*"
                it.repeated = it.repeated or suffix in "*+"
        if is_choice:
            for it in items:
                it.optional = True
        return items, is_choice

    if not tokens or tokens[0] != "(":
        return []
    items, _ = parse_group()
    merged: dict[str, ChildSpec] = {}
    order = 0
    for it in items:
        if it.name in merged:
            merged[it.name].repeated = True
        else:
            it.order = order
            order += 1
            merged[it.name] = it
    return list(merged.values())


# ------------------------------------------------------------- name mangling


def pascal(name: str) -> str:
    parts = re.split(r"[_\W]+", name)
    out = ""
    for p in parts:
        if not p:
            continue
        if p.isupper() and len(p) > 1:  # DOM, SN, ID, UI...
            out += p[0] + p[1:].lower()
        else:
            out += p[0].upper() + p[1:]
    return out


def lower_camel(name: str) -> str:
    p = pascal(name)
    return p[0].lower() + p[1:]


# ------------------------------------------------------------------ emitters


def emit_message_types_h(messages: list[dict]) -> str:
    lines = [BANNER, "#pragma once", ""]
    lines += [
        "#include <cstdint>",
        "#include <span>",
        "#include <string_view>",
        "",
        "#include <imos/core_export.h>",
        "#include <imos/protocol.h>",
        "",
        "namespace imos::codec {",
        "",
        "/// Every message of the MOS v4.0 vocabulary (plan §3.2), the thirteen",
        "/// legacy messages removed in 4.0 (parse/normalize only), and the",
        "/// chapter-5 web-control plug-in family.",
        "enum class MessageType : std::uint8_t {",
        "    Unknown = 0,",
    ]
    for m in messages:
        lines.append(f"    {m['enum']},")
    lines += [
        "};",
        "",
        f"inline constexpr std::size_t kMessageTypeCount = {len(messages) + 1};"
        "  // incl. Unknown",
        "",
        "/// Static per-message metadata captured from the spec's per-message",
        "/// annotations (Port, Profile, Response) via tools/codegen.",
        "struct MessageInfo {",
        "    MessageType type = MessageType::Unknown;",
        "    std::string_view wireName;",
        "    ChannelAffinity channel = ChannelAffinity::AnyChannel;",
        "    std::int8_t profile = -1;  ///< -1: not a profile member",
        "    EnvelopeKind envelope = EnvelopeKind::Full;",
        "    bool isAck = false;          ///< completes exchanges, never opens one",
        "    bool legacyRemoved = false;  ///< removed in 4.0; receive-and-normalize only",
        "    bool plugin = false;         ///< host↔plug-in message, not network traffic",
        "    std::span<const MessageType> responses;  ///< replies completing the exchange",
        "};",
        "",
        "/// Metadata for a message type. `MessageType::Unknown` yields a",
        "/// placeholder entry with an empty wire name.",
        "IMOS_CORE_API const MessageInfo& messageInfo(MessageType type) noexcept;",
        "",
        "/// Wire-name lookup (exact match); MessageType::Unknown if unrecognized.",
        "IMOS_CORE_API MessageType messageTypeFromName(std::string_view wireName) noexcept;",
        "",
        "}  // namespace imos::codec",
    ]
    return "\n".join(lines) + "\n"


CHANNEL_CPP = {
    "mom": "ChannelAffinity::Mom",
    "ro": "ChannelAffinity::Ro",
    "aux": "ChannelAffinity::Aux",
    "any": "ChannelAffinity::AnyChannel",
    "none": "ChannelAffinity::NotNetwork",
}
ENVELOPE_CPP = {"full": "EnvelopeKind::Full", "ids": "EnvelopeKind::IdsOnly",
                "none": "EnvelopeKind::None"}


def emit_message_types_cpp(messages: list[dict]) -> str:
    lines = [BANNER]
    lines += [
        "#include <imos/codec/gen/message_types.h>",
        "",
        "#include <array>",
        "",
        "namespace imos::codec {",
        "namespace {",
        "",
    ]
    for m in messages:
        if m["responses"]:
            resp = ", ".join(f"MessageType::{r}" for r in m["responses"])
            lines.append(
                f"constexpr MessageType kResponses{m['enum']}[] = {{{resp}}};")
    lines += [
        "",
        f"constexpr std::array<MessageInfo, {len(messages) + 1}> kMessageInfos = {{{{",
        '    {MessageType::Unknown, "", ChannelAffinity::AnyChannel, -1,'
        " EnvelopeKind::Full, false,",
        "     false, false, {}},",
    ]
    for m in messages:
        resp = f"kResponses{m['enum']}" if m["responses"] else "{}"
        lines.append(
            f"    {{MessageType::{m['enum']}, \"{m['name']}\", {CHANNEL_CPP[m['channel']]},"
            f" {m['profile']}, {ENVELOPE_CPP[m['envelope']]},")
        lines.append(
            f"     {str(m['isAck']).lower()}, {str(m['legacyRemoved']).lower()},"
            f" {str(m['plugin']).lower()}, {resp}}},")
    lines += [
        "}};",
        "",
        "}  // namespace",
        "",
        "const MessageInfo& messageInfo(MessageType type) noexcept {",
        "    const auto index = static_cast<std::size_t>(type);",
        "    return kMessageInfos[index < kMessageInfos.size() ? index : 0];",
        "}",
        "",
        "MessageType messageTypeFromName(std::string_view wireName) noexcept {",
        "    for (const MessageInfo& info : kMessageInfos) {",
        "        if (!info.wireName.empty() && info.wireName == wireName) {",
        "            return info.type;",
        "        }",
        "    }",
        "    return MessageType::Unknown;",
        "}",
        "",
        "}  // namespace imos::codec",
    ]
    return "\n".join(lines) + "\n"


def emit_views_h(decls: dict[str, ElementDecl], view_elements: list[str]) -> str:
    lines = [BANNER, "#pragma once", ""]
    lines += [
        "#include <cstddef>",
        "#include <optional>",
        "#include <span>",
        "#include <string_view>",
        "",
        "#include <imos/codec/xml.h>",
        "",
        "// Typed accessor views over the retained XML tree (plan §4.5). A view",
        "// borrows an element node; getters are lenient (missing child ->",
        "// nullopt), setters create missing children at their content-model",
        "// position. Mixed-content and ANY children (storyBody paragraphs,",
        "// mosPayload, mosAbstract, description) stay raw XmlNode access so",
        "// opaque payloads are never re-normalized.",
        "",
        "namespace imos::codec::view {",
        "",
    ]
    for name in view_elements:
        decl = decls[name]
        cls = pascal(name)
        order_names = ", ".join(f'"{c.name}"' for c in decl.children)
        lines.append(f"class {cls} {{")
        lines.append("public:")
        lines.append(f'    static constexpr std::string_view kElementName = "{name}";')
        lines.append(f"    explicit {cls}(XmlNode& node) : node_(&node) {{}}")
        lines.append("    [[nodiscard]] XmlNode& node() const { return *node_; }")
        if decl.kind == "scalar":
            lines.append(
                "    [[nodiscard]] std::string_view text() const"
                " { return node_->text(); }")
            lines.append(
                "    void setText(std::string_view v) { node_->setText(v); }")
        for attr in decl.attributes:
            ap = pascal(attr)
            lines.append(
                f"    [[nodiscard]] std::optional<std::string_view> attr{ap}() const"
                f' {{ return node_->attribute("{attr}"); }}')
            lines.append(
                f"    void setAttr{ap}(std::string_view v)"
                f' {{ node_->setAttribute("{attr}", v); }}')
        for c in decl.children:
            child = decls.get(c.name)
            # Scalars with declared attributes (objPath techDescription, ...)
            # keep node access so the attributes stay reachable via their view.
            child_kind = child.kind if child and not child.attributes else "struct"
            cp = pascal(c.name)
            cc = lower_camel(c.name)
            if child_kind == "scalar" and not c.repeated:
                lines.append(
                    f"    [[nodiscard]] std::optional<std::string_view> {cc}() const"
                    f' {{ return detail::childText(*node_, "{c.name}"); }}')
                lines.append(
                    f"    void set{cp}(std::string_view v)"
                    f' {{ detail::setChildText(*node_, "{c.name}", v, kChildOrder); }}')
            elif child_kind == "scalar" and c.repeated:
                lines.append(
                    f"    [[nodiscard]] std::size_t {cc}Count() const"
                    f' {{ return node_->countChildElements("{c.name}"); }}')
                lines.append(
                    f"    [[nodiscard]] std::optional<std::string_view> {cc}(std::size_t i) const"
                    " {")
                lines.append(
                    f'        return detail::childTextAt(*node_, "{c.name}", i);')
                lines.append("    }")
                lines.append(f"    XmlNode& add{cp}(std::string_view v) {{")
                lines.append(
                    f'        return detail::appendChildText(*node_, "{c.name}", v,'
                    " kChildOrder);")
                lines.append("    }")
            elif c.repeated:
                lines.append(
                    f"    [[nodiscard]] std::size_t {cc}Count() const"
                    f' {{ return node_->countChildElements("{c.name}"); }}')
                lines.append(
                    f"    [[nodiscard]] XmlNode* {cc}(std::size_t i) const"
                    f' {{ return node_->childElementAt("{c.name}", i); }}')
                lines.append(
                    f"    XmlNode& add{cp}()"
                    f' {{ return detail::appendChild(*node_, "{c.name}", kChildOrder); }}')
            else:
                lines.append(
                    f"    [[nodiscard]] XmlNode* {cc}() const"
                    f' {{ return node_->firstChildElement("{c.name}"); }}')
                lines.append(
                    f"    XmlNode& ensure{cp}()"
                    f' {{ return detail::ensureChild(*node_, "{c.name}", kChildOrder); }}')
        lines.append("")
        lines.append("private:")
        if decl.children:
            lines.append(
                f"    static constexpr std::string_view kChildOrder[] = {{{order_names}}};")
        else:
            lines.append("    static constexpr std::span<const std::string_view>"
                         " kChildOrder{};")
        lines.append("    XmlNode* node_;")
        lines.append("};")
        lines.append("")
    lines.append("}  // namespace imos::codec::view")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------- main


def main() -> int:
    if len(sys.argv) != 4:
        print(__doc__, file=sys.stderr)
        return 2
    dtd_path, ann_path, out_root = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])

    decls = parse_dtd(dtd_path.read_text(encoding="utf-8"))
    ann = json.loads(ann_path.read_text(encoding="utf-8"))

    for name, model in ann["supplementalContentModels"].items():
        decls[name] = ElementDecl(name, model, attributes=decls.get(
            name, ElementDecl(name, model)).attributes)
    for decl in decls.values():
        decl.children = flatten_model(decl.model)

    messages = []
    for name, a in ann["messages"].items():
        if name not in decls:
            print(f"error: message '{name}' has no content model", file=sys.stderr)
            return 1
        messages.append({
            "name": name,
            "enum": pascal(name),
            "channel": a["channel"],
            "profile": a["profile"] if a["profile"] is not None else -1,
            "envelope": a.get("envelope", "full"),
            "isAck": a.get("isAck", False),
            "legacyRemoved": a.get("legacyRemoved", False),
            "plugin": a.get("plugin", False),
            "responses": [pascal(r) for r in a["responses"]],
        })

    skip = set(ann["viewSkipElements"])
    message_names = list(ann["messages"].keys())
    referenced: list[str] = []

    def visit(name: str) -> None:
        decl = decls.get(name)
        if decl is None or name in skip or name in referenced:
            return
        if decl.kind in ("scalar",) and not decl.attributes:
            return  # plain text leaf: no view needed
        if decl.kind == "mixed":
            return  # raw XmlNode access only
        referenced.append(name)
        for c in decl.children:
            visit(c.name)

    for name in message_names:
        visit(name)

    outputs = {
        out_root / "include/imos/codec/gen/message_types.h":
            emit_message_types_h(messages),
        out_root / "include/imos/codec/gen/views.h": emit_views_h(decls, referenced),
        out_root / "codec/gen/message_types.cpp": emit_message_types_cpp(messages),
    }
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
